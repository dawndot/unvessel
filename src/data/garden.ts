// ============================================================
// garden.ts — 自留地·爱好区数据（/garden 页面数据源之一）
// ============================================================
// 「文件即接口」在自留地的体现：加一条爱好 = 在 GARDEN 数组加一条 + build。
// 门类不做枚举——kind 是自由字符串，页面按 kind 自动分组，
// 新增一个爱好门类（电影 / 咖啡 / 桌游…）不需要改任何代码，
// 删光某门类的条目 = 该分组自动消失。
//
// 状态机（对齐 works.ts 的三态语义）：
//   doing — 进行中（在读 / 在听 / 在玩），朱砂实心点
//   done  — 记录完毕（烟灰空心点）
//   wish  — 愿望单（想要 / 计划），呼吸点
//
// 链接纪律（沿用 works.ts）：link 只在有「真实目标」时填
//   （豆瓣条目 / Spotify 专辑 / 仓库主页…），没有就省略——
//   纯展示条目绝不硬塞一个不相干的链接。
// ============================================================

export type GardenStatus = 'doing' | 'done' | 'wish';

export interface GardenItem {
  /** 门类：读书 / 音乐 / 电影 / 游戏…（自由字符串，页面按值自动分组） */
  kind: string;
  /** 条目名：书名 / 专辑名 / 影名… */
  title: string;
  /** 元信息：作者 / 艺术家 / 年份…（等宽字展示） */
  meta: string;
  /** 一句话笔记：为什么记下它、当时的感受 */
  note: string;
  /** 状态：doing 进行中 / done 记录完毕 / wish 愿望单 */
  status: GardenStatus;
  /** 真实外链（可选）：豆瓣 / Spotify / Bandcamp… 没有就整条省略 */
  link?: string;
  /** 记录日期：ISO 字符串（YYYY-MM-DD），组内按它倒序排列 */
  date: string;
}

